"""The results table: the same lap through the same link, with the link made worse each row.

Latency here is simulated link time, counted on the simulation's clock. It does not depend on
how fast the computer is. The machine only decides how long a row takes to run.
"""

from __future__ import annotations

import json
import platform
import time
from dataclasses import dataclass
from typing import Any

import cantools

from pitwall.metrics import Metrics
from pitwall.pipeline import Pipeline, RunConfig

DURATION_S = 40.0
SEED = 2026
OUTAGE = (12.0, 17.0)


@dataclass(frozen=True)
class Row:
    label: str
    config: RunConfig
    command: str


ROWS = (
    Row("0% loss", RunConfig(seed=SEED, duration_s=DURATION_S), "uv run python -m pitwall run"),
    Row(
        "5% loss",
        RunConfig(seed=SEED, duration_s=DURATION_S, loss=0.05),
        "uv run python -m pitwall run --loss 5",
    ),
    Row(
        "10% loss",
        RunConfig(seed=SEED, duration_s=DURATION_S, loss=0.10),
        "uv run python -m pitwall run --loss 10",
    ),
    Row(
        "20% loss",
        RunConfig(seed=SEED, duration_s=DURATION_S, loss=0.20),
        "uv run python -m pitwall run --loss 20",
    ),
    Row(
        "5 s outage",
        RunConfig(seed=SEED, duration_s=DURATION_S, outages_s=(OUTAGE,)),
        "uv run python -m pitwall run --outage 12:17",
    ),
    Row(
        "5 s outage, 500-frame buffer",
        RunConfig(seed=SEED, duration_s=DURATION_S, outages_s=(OUTAGE,), buffer=500),
        "uv run python -m pitwall run --outage 12:17 --buffer 500",
    ),
)


@dataclass(frozen=True)
class Result:
    row: Row
    metrics: Metrics
    generated: int
    delivered: int
    lost: int
    resends: int
    wall_s: float


def run_row(row: Row) -> Result:
    pipeline = Pipeline(row.config)
    started = time.perf_counter()
    metrics = pipeline.run_to_end()
    wall = time.perf_counter() - started
    assert pipeline.session is not None
    s = pipeline.session
    return Result(
        row,
        metrics,
        s.generated,
        s.receiver.stats.delivered,
        s.receiver.stats.lost,
        s.sender.stats.resends,
        wall,
    )


def machine() -> dict[str, str]:
    cpu = "unknown CPU"
    try:
        with open("/proc/cpuinfo", encoding="utf-8") as f:
            for line in f:
                if line.startswith("model name"):
                    cpu = line.split(":", 1)[1].strip()
                    break
    except OSError:
        cpu = platform.processor() or cpu
    return {
        "cpu": cpu,
        "os": f"{platform.system()} {platform.release()}",
        "python": platform.python_version(),
        "cantools": cantools.__version__,
    }


def _ms(value: float | None) -> str:
    return "n/a" if value is None else f"{value:,.0f}"


def _seconds(value: float | None) -> str:
    return "n/a" if value is None else f"{value / 1000:.2f}"


def table(results: list[Result]) -> str:
    lines = [
        "| Row | p50 (ms) | p95 (ms) | Longest silence (s) | Back to live (s) | "
        "Frames lost | Resends | Command |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for r in results:
        m = r.metrics
        lines.append(
            f"| {r.row.label} | {_ms(m.p50_ms)} | {_ms(m.p95_ms)} | {_seconds(m.longest_gap_ms)} | "
            f"{_seconds(m.back_to_live_ms)} | {r.lost} of {r.generated} | {r.resends:,} | "
            f"`{r.row.command}` |"
        )
    return "\n".join(lines)


def to_json(results: list[Result]) -> dict[str, Any]:
    return {
        "machine": machine(),
        "seed": SEED,
        "duration_s": DURATION_S,
        "rows": [
            {
                "label": r.row.label,
                "command": r.row.command,
                "metrics": r.metrics.as_dict(),
                "generated": r.generated,
                "delivered": r.delivered,
                "lost": r.lost,
                "resends": r.resends,
                "wall_s": round(r.wall_s, 2),
            }
            for r in results
        ],
    }


def markdown(results: list[Result]) -> str:
    m = machine()
    wall = ", ".join(f"{r.wall_s:.1f}" for r in results)
    return (
        "# Results\n\n"
        "Generated by `uv run python -m pitwall bench --write docs/RESULTS.md`. "
        "Do not edit by hand.\n\n"
        f"Every row is the same {DURATION_S:.0f} second lap (seed {SEED}) over a link with "
        "40 ms delay and up to 8 ms jitter, in each direction. "
        "Latency is simulated link time.\n\n" + table(results) + "\n\n"
        f"Machine: {m['cpu']}, {m['os']}, Python {m['python']}, cantools {m['cantools']}.\n"
        f"Wall-clock seconds to run each row on that machine: {wall}.\n"
        "\nOnly the machine line and the wall-clock line change from computer to computer. "
        "The table does not.\n"
    )


def json_dump(results: list[Result]) -> str:
    return json.dumps(to_json(results), indent=2)
